<?php

/**
 * 管理 API 全体で使う設定、共通レスポンス、初期化処理をまとめます。
 *
 * 主な流れ:
 * 1. リクエストやセッションなど、処理に必要な情報を読み取る
 * 2. 入力値や権限を確認し、必要に応じてデータベースへ問い合わせる
 * 3. 処理結果を JSON などの形でフロントエンドへ返す
 *
 * 扱うデータ: アプリの設定値や、他のファイルから受け取る値を主に扱います。
 */

// 設定配列 → 環境変数 → デフォルト値の順で値を決めます。
/**
 * 環境変数や設定配列から指定された設定値を取り出します。
 *
 * @param string $key 呼び出し元から渡される処理対象の値です。
 * @param $default = null 呼び出し元から渡される処理対象の値です。
 * @return 戻り値の型は明示されていません。echo、配列、または副作用で結果を扱います。
 * エラー処理は主に呼び出し元、またはこの関数を使うAPI本体側で行います。
 */
function app_config(string $key, $default = null)
{
    global $config;
        // まず設定配列を見て、空でなければそれを優先します。
    if (!empty($config[$key])) {
        return $config[$key];
    }
        // 設定配列に無い場合は、環境変数から読みます。
    $envValue = getenv($key);
    return $envValue !== false && $envValue !== "" ? $envValue : $default;
}

